import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEFAULT_ENGINE_CONFIG, runVisitEngine } from '../src/visit';
import { buildVisitScenarios } from '../test/visitScenarios';

export const VECTORS_PATH = fileURLToPath(new URL('../../../sdk/spec/vectors/visit-engine.json', import.meta.url));
const FIXTURE = fileURLToPath(new URL('../test/fixtures/moo-2026-11-13-iphone.csv', import.meta.url));

/** The shared vectors as JSON text (stable formatting, so a diff shows real changes). */
export function buildVectorsJson(): string {
  const scenarios = buildVisitScenarios(readFileSync(FIXTURE, 'utf8')).map((s) => ({
    name: s.name,
    description: s.description,
    venues: s.venues,
    inputs: s.inputs,
    expected: runVisitEngine(s.venues, s.inputs, DEFAULT_ENGINE_CONFIG),
  }));
  const doc = {
    format: 'locus-visit-engine-vectors',
    version: 1,
    note: 'Generated by packages/altitude-core/scripts/gen-vectors.ts from the TypeScript reference (src/visit.ts). Do not edit by hand. Compare every field exactly except baselinePressureHpa (absolute tolerance 1e-6).',
    config: DEFAULT_ENGINE_CONFIG,
    scenarios,
  };
  return JSON.stringify(doc, null, 1) + '\n';
}
